#!/usr/bin/env python3
"""NTSC part 1 at 60 Hz: every NTSC frame n shows the film at time 5n/6 (the film keeps its length), all frames
from the stream (no procedural part: part1.frame_list at fractional times + part1_proc's dimming maps).
Writes the same files as part1p_gen.py (part1p.inc with T_PROC = 0, part1p_rec.bin, part1p_prof.bin, part1p.cfg)
and /tmp/part1n_bufs.pkl (the LINEBUF of every frame: the model).

    python3 part1n_gen.py
"""
import pickle
import part1p_gen as g
import part1 as p1
import part1_proc as q

H = 200
BUDGET = 3800
NN = (p1.T_END - 1) * 6 // 5 + 1

def tau(n):
    return n * 5 / 6

def frame_bars(n):
    t = tau(n)
    out = []
    for y0, T in p1.frame_list(t):
        if t < p1.T_STACK:
            ti = int(round(t))
            di = q.DX[ti - q.DIM0] if q.DIM0 <= ti < q.DIM0 + q.DIMN else 0
            base = [q.DIMT[di][f >> 5][f & 31] for f in q.FULL[T]]
        else:
            base = list(p1.gp.PROF[T])
        out.append((y0, T, base))
    return out

def stream():
    """Per frame: runs of rows that differ from the previous frame's LINEBUF; each run is a slice of ONE bar array
    (the bar that is on top there) or of a block of zeros.  Record: [n] n x (src lo, src hi, first line, rows - 1)."""
    prof, off = bytearray(), {}
    def intern(a):
        k = bytes(a)
        if k not in off:
            off[k] = len(prof); prof.extend(k)
        return off[k]
    ZERO = bytes(H)
    intern(ZERO)
    runs_all, bufs, prev, stale = [], [], [0] * H, []
    for n in range(NN):
        buf, own = [0] * H, [None] * H
        for y0, T, base in frame_bars(n):                       # far first: the nearer bar wins
            arr = bytes((k + 32 * (y0 & 1)) if k else 0 for k in base)
            for i, k in enumerate(arr):
                y = y0 + i
                if 0 <= y < H and k:
                    buf[y] = k; own[y] = (arr, i)
        runs, y = [], 0
        while y < H:
            if buf[y] == prev[y]:
                y += 1; continue
            if own[y] is None:                                  # rows that become black
                y1 = y
                while y1 < H and own[y1] is None and buf[y1] != prev[y1]: y1 += 1
                for s0 in range(y, y1, 128): runs.append((ZERO, 0, s0, min(y1, s0 + 128) - s0))
            else:
                arr, i0 = own[y]
                y1 = y
                while y1 < H and own[y1] is not None and own[y1][0] is arr and own[y1][1] == i0 + (y1 - y) and buf[y1] != prev[y1]: y1 += 1
                runs.append((arr, i0, y, y1 - y))
            y = y1
        # the budget: the blank holds ~3.6 k cycles; the rest is caught up in the next frame (stale lines)
        chosen, used, state = [], 150, list(prev)
        for r in sorted(runs, key=lambda r: -r[3]):
            c = 14 * r[3] + 75
            if used + c <= BUDGET:
                chosen.append(r); used += c
                arr, i0, y, n_ = r
                state[y:y + n_] = list(arr[i0:i0 + n_])
        chosen.sort(key=lambda r: r[2])
        stale.append(sum(state[y] != buf[y] for y in range(H)))
        runs_all.append(chosen); bufs.append(state); prev = state
    for runs in runs_all:
        for arr, i0, y, n_ in runs:
            intern(arr)
    late = [n for n in range(NN) if stale[n]]
    print(f'frames with stale lines: {len(late)}, max {max(stale)} lines')
    return runs_all, bytes(prof), off, bufs

CFG = """# generated by part1n_gen.py -- part 1, NTSC 60 Hz (no procedural tables; the records are in ROM banks)
MEMORY {{
    ZP:       start = $0002, size = $00FE, type = rw;
    LOADADDR: start = $07FF, size = $0002, file = %O;
    MAIN:     start = $0801, size = $1800 - $0801, file = %O, fill = yes;
    TAB:      start = $1800, size = $0800, file = %O, fill = yes;
    ROWS0:    start = $2000, size = $1000, file = %O, fill = yes;
    ROWS1:    start = $3000, size = $1000, file = %O, fill = yes;
    PROF:     start = $4000, size = $4000, file = %O, fill = yes;
    GAP:      start = $8000, size = $4000, file = %O, fill = yes;
    PROF2:    start = $C000, size = {p2}, file = %O;
}}
SEGMENTS {{
    ZEROPAGE: load = ZP,       type = zp;
    LOADADDR: load = LOADADDR, type = ro;
    EXEHDR:   load = MAIN,     type = ro;
    CODE:     load = MAIN,     type = rw;
    TABLES:   load = TAB,      type = ro, align = $100;
    ROWS0:    load = ROWS0,    type = rw;
    ROWS1:    load = ROWS1,    type = rw;
    PROF:     load = PROF,     type = ro;
    PROF2:    load = PROF2,    type = ro;
}}
"""

def place(arrays):
    """addresses for the arrays: $4000-$7FFF, then $C000-$CFFF (outside the cartridge window $8000-$BFFF)."""
    regs, cur, addr = [bytearray(), bytearray()], 0, {}
    for a in sorted(arrays, key=len, reverse=True):
        if cur == 0 and len(regs[0]) + len(a) > 0x4000: cur = 1
        base = 0x4000 if cur == 0 else 0xC000
        addr[a] = base + len(regs[cur]); regs[cur] += a
    assert len(regs[1]) <= 0x1000
    return addr, regs

def main():
    runs_all, prof, off, bufs = stream()
    addr, regs = place(list(off))
    banks, cur = [], bytearray()
    for runs in runs_all:
        assert len(runs) < 250
        r = bytearray([len(runs)])
        for arr, i0, y, n_ in runs:
            assert n_ <= 128
            ptr = addr[arr] + i0
            r += bytes([ptr & 255, ptr >> 8, y, n_ - 1])
        if len(cur) + len(r) > 0x4000 - 1:
            cur.append(0xFE); banks.append(bytes(cur).ljust(0x4000, b"\xff")); cur = bytearray()
        cur += r
    banks.append(bytes(cur).ljust(0x4000, b"\xff"))
    open("part1n_str.bin", "wb").write(b"".join(banks))
    open("part1n_prof0.bin", "wb").write(bytes(regs[0])); open("part1n_prof1.bin", "wb").write(bytes(regs[1]) or b"\0")
    open("part1n.cfg", "w").write(CFG.format(p2=max(1, len(regs[1]))))
    col, gh = g.swatch_tables()
    with open("part1n.inc", "w") as f:
        f.write("; generated by part1n_gen.py -- do not edit\n")
        f.write(f"T_END = {NN}\nIMGBANKS = 4\n")
        for name, tabs in (("colt", col), ("ght", gh)):
            f.write(f".macro {name.upper()}\n")
            for t_ in tabs:
                f.write("        .byte " + ",".join(str(v & 255) for v in t_) + "\n")
            f.write(".endmacro\n")
    pickle.dump(bufs, open("/tmp/part1n_bufs.pkl", "wb"))
    cost = [sum(14 * n_ + 75 for _, _, _, n_ in r) + 150 for r in runs_all]
    print(f"{NN} frames; arrays {len(regs[0])} + {len(regs[1])} B, stream {len(banks)} banks of 16 KB; est. update worst {max(cost)} cycles, frames over 3500: {sum(c > 3500 for c in cost)}")

if __name__ == "__main__":
    main()
