#!/usr/bin/env python3
"""Generator for part1.prg (the intro film on the C64: ghost-byte swatches, no splits).

 part1.inc       constants and the swatch tables (colour and idle byte by swatch, frame parity
                 and line parity: v10 ramp, 25 swatches)
 part1_prof.bin  every bar thickness 1..63 as its swatch indices, top row first (0 = black)
 part1_rec.bin   the scene frame by frame: each bar far to near, 4 bytes (address of its
                 first visible non-black index in the profile table, first line, rows - 1);
                 $ff = same list as last frame

    python3 part1_gen.py
"""
import numpy as np
import part1 as p1
import preview_v10 as v10

gp = p1.gp
TMAX = gp.TMAX
PROF_BASE = 0x2000
LAD = gp.LAD
H = 200

def visible(y0, T):
    rows = [i for i in range(T) if gp.PROF[T][i] and 0 <= y0 + i < H]
    if rows:
        assert rows == list(range(rows[0], rows[-1] + 1)), "black row inside a bar"
    return (rows[0], rows[-1]) if rows else None

def build():
    lists = [p1.frame_list(f) for f in range(p1.T_END)]
    prof, off = bytearray(), {}
    for T in range(1, TMAX + 1):
        off[T] = len(prof)
        prof += bytes(gp.PROF[T])
    rec, prev = bytearray(), None
    for lst in lists:
        if lst == prev:
            rec.append(0xFF)
        else:
            rec.append(len(lst))
            for y0, T in lst:
                r0, r1 = visible(y0, T)
                ptr = PROF_BASE + off[T] + r0
                rec += bytes([ptr & 255, ptr >> 8, y0 + r0, r1 - r0])
        prev = lst
    return lists, bytes(rec), bytes(prof)

def compose_ref(lst):
    buf = [0] * H
    for y0, T in lst:
        for i, k in enumerate(gp.PROF[T]):
            if k and 0 <= y0 + i < H:
                buf[y0 + i] = k
    return buf

def tables():
    col, gh = [], []
    for fp in (0, 1):
        for rp in (0, 1):
            col.append([v10.colour(k, rp, fp) for k in LAD])
            gh.append([v10.ghost(k, rp, fp) for k in LAD])
    return col, gh                                       # index fp * 2 + rp

def main():
    lists, rec, prof = build()
    open("part1_rec.bin", "wb").write(rec)
    open("part1_prof.bin", "wb").write(prof)
    col, gh = tables()
    with open("part1.inc", "w") as f:
        f.write("; generated by part1_gen.py -- do not edit\n")
        f.write(f"T_END = {p1.T_END}\nTMAX = {TMAX}\nNSW = {len(LAD)}\n")
        for name, tabs in (("colt", col), ("ght", gh)):
            f.write(f".macro {name.upper()}\n")
            for t in tabs:
                f.write("        .byte " + ",".join(str(v & 255) for v in t) + ",0,0,0,0,0,0,0\n")   # 32 a table
            f.write(".endmacro\n")
    print(f"{p1.T_END} frames, up to {max(len(l) for l in lists)} bars; "
          f"records {len(rec)} bytes, profiles {len(prof)} bytes")

if __name__ == "__main__":
    main()
