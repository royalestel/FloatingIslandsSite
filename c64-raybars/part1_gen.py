#!/usr/bin/env python3
"""Generator for part1.prg (the intro film on the C64: ghost-byte swatches, no splits).

 part1.inc       constants and the swatch tables (colour and idle byte by swatch, frame parity
                 and line parity: v10 ramp, 25 swatches)
 part1_prof.bin  every bar thickness 1..63 as its swatch indices, top row first (0 = black)
 part1_rec.bin   the scene frame by frame: each bar far to near, 4 bytes (address of its
                 first visible non-black index in the profile table, first line, rows - 1);
                 $ff = same list as last frame

    python3 part1_gen.py
"""
import numpy as np
import part1 as p1
import preview_v10 as v10

gp = p1.gp
TMAX = gp.TMAX
PROF_BASE = 0x4000                    # the deduplicated bar arrays
IO = 0xD000                           # the scene stream jumps over $d000-$dfff (I/O) to $e000
SCENE1 = 0xE000
LAD = gp.LAD
H = 200

def dim_state(f):
    g = p1.dim(f)
    return g, ((1.0 - g) / (1.0 - p1.DIM[1][1]) if g < 1.0 else 0.0)

def bar_array(T, f):
    """The swatch indices of one bar at frame f, top row first: the bar's profile, with the dimming
    of the circling section applied (fade down the ramp; the middle 4 rows of the bar one swatch
    lighter and every bright row held on a 6-swatch ramp) -- part1.py's dimk, per bar."""
    arr = list(gp.PROF[T])
    g, u = dim_state(f)
    if g >= 1.0:
        return arr
    nz = [i for i, k in enumerate(arr) if k]
    cen = set()
    if len(nz) >= 8:
        m = (nz[0] + nz[-1] + 1) // 2
        cen = set(range(m - 2, m + 2))
    out = []
    for i, k in enumerate(arr):
        if not k:
            out.append(0)
            continue
        v = k * g
        if k >= 16:
            v = max(v, k * (1 - u) + (11 + k - 16 + (1 if i in cen else 0)) * u)
        out.append(max(1, int(round(v))))
    return out

def visible(arr, y0):
    rows = [i for i, k in enumerate(arr) if k and 0 <= y0 + i < H]
    if rows:
        assert rows == list(range(rows[0], rows[-1] + 1)), "black row inside a bar"
    return (rows[0], rows[-1]) if rows else None

def build():
    lists = [p1.frame_list(f) for f in range(p1.T_END)]
    prof, off = bytearray(), {}
    def intern(arr):
        key = bytes(arr)
        if key not in off:
            off[key] = len(prof)
            prof.extend(key)
        return off[key]
    frames, prev = [], None
    for f, lst in enumerate(lists):
        arrs = [(y0, bar_array(T, f)) for y0, T in lst]
        key = [(y0, tuple(a)) for y0, a in arrs]
        if key == prev:
            frames.append(None)
        else:
            vis = [(y0, a, visible(a, y0)) for y0, a in arrs]
            frames.append([(y0, a, v) for y0, a, v in vis if v])
        prev = key
    for fr in frames:                                     # intern the profiles first: their size sets the layout
        for y0, a, v in fr or []:
            intern(a)
    scene0_start = PROF_BASE + len(prof)
    rec0, rec1 = bytearray(), bytearray()
    for fr in frames:
        if fr is None:
            body = bytes([0xFF])
        else:
            body = bytearray([len(fr)])
            for y0, a, (r0, r1) in fr:
                ptr = PROF_BASE + off[bytes(a)] + r0
                body += bytes([ptr & 255, ptr >> 8, y0 + r0, r1 - r0])
        if not rec1 and scene0_start + len(rec0) + len(body) > IO - 1:
            rec0.append(0xFE)                             # jump to scene1; a record never straddles the hole
        (rec1 if (rec1 or rec0[-1:] == b"\xfe") else rec0).extend(body)
    return lists, bytes(rec0), bytes(rec1), bytes(prof)

def compose_ref(lst, f):
    buf = [0] * H
    for y0, T in lst:
        for i, k in enumerate(bar_array(T, f)):
            if k and 0 <= y0 + i < H:
                buf[y0 + i] = k
    return buf

def tables():
    col, gh = [], []
    for fp in (0, 1):
        for rp in (0, 1):
            col.append([v10.colour(k, rp, fp) for k in LAD])
            gh.append([v10.ghost(k, rp, fp) for k in LAD])
    return col, gh                                       # index fp * 2 + rp

CFG = """# generated by part1_gen.py -- ld65 config for part1.prg: BASIC "SYS 2061" stub; everything in the PRG.
#  $0801 code   $1800 swatch tables   $2000 row set (even frames)   $3000 row set (odd frames)
#  $4000 deduplicated bar arrays ({prof_size} bytes)   then the scene stream up to $d000, the I/O hole
#  (RAM under it, filled), and the rest of the stream from $e000.  $3FFF is the VIC's idle byte.
#  The 200-byte line buffer is at $0400 (the screen is never shown).
MEMORY {{
    ZP:       start = $0002, size = $00FE, type = rw;
    LOADADDR: start = $07FF, size = $0002, file = %O;
    MAIN:     start = $0801, size = $1800 - $0801, file = %O, fill = yes;
    TAB:      start = $1800, size = $0800, file = %O, fill = yes;
    ROWS0:    start = $2000, size = $1000, file = %O, fill = yes;
    ROWS1:    start = $3000, size = $1000, file = %O, fill = yes;
    PROF:     start = $4000, size = {prof_size}, file = %O, fill = yes;
    SCENE0:   start = {scene0}, size = {scene0_size}, file = %O, fill = yes;
    HOLE:     start = $D000, size = {gap}, file = %O, fill = yes;
    SCENE1:   start = $E000, size = {scene1_size}, file = %O;
}}
SEGMENTS {{
    ZEROPAGE: load = ZP,       type = zp;
    LOADADDR: load = LOADADDR, type = ro;
    EXEHDR:   load = MAIN,     type = ro;
    CODE:     load = MAIN,     type = rw;
    TABLES:   load = TAB,      type = ro, align = $100;
    ROWS0:    load = ROWS0,    type = rw;
    ROWS1:    load = ROWS1,    type = rw;
    PROF:     load = PROF,     type = ro;
    SCENE:    load = SCENE0,   type = ro;
    SCENE1:   load = SCENE1,   type = ro;
}}
"""

def main():
    lists, rec0, rec1, prof = build()
    open("part1_rec0.bin", "wb").write(rec0)
    open("part1_rec1.bin", "wb").write(rec1)
    open("part1_prof.bin", "wb").write(prof)
    s0 = PROF_BASE + len(prof)
    open("part1.cfg", "w").write(CFG.format(prof_size=len(prof), scene0=s0, scene0_size=IO - s0,
                                          gap=SCENE1 - IO, scene1_size=0xFFFA - SCENE1))
    col, gh = tables()
    with open("part1.inc", "w") as f:
        f.write("; generated by part1_gen.py -- do not edit\n")
        f.write(f"T_END = {p1.T_END}\nTMAX = {TMAX}\nNSW = {len(LAD)}\n")
        for name, tabs in (("colt", col), ("ght", gh)):
            f.write(f".macro {name.upper()}\n")
            for t in tabs:
                f.write("        .byte " + ",".join(str(v & 255) for v in t) + ",0,0,0,0,0,0,0\n")   # 32 a table
            f.write(".endmacro\n")
    print(f"{p1.T_END} frames, up to {max(len(l) for l in lists)} bars; "
          f"records {len(rec0)} + {len(rec1)} bytes, profiles {len(prof)} bytes")

if __name__ == "__main__":
    main()
