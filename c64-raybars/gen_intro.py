#!/usr/bin/env python3
"""intro.inc: cosmicstrings's start in the cartridge (INTRO = CHAIN): goldfly's light (the largest ball) shrinks, splits in two that glide to the
ship's two engine lights, then the rest of the ship fades in; after that the bars come in (the depth front, cosmicstrings.s).

Sprite blocks (segment INTROSPR, $A000 = bank 2 block $80; not $9000-$9FFF, where the VIC sees the character ROM): the 8 balls of orbit.inc
(blocks $80-$87: goldfly's light is $87), then the ship's level frame (pitch 4) for both frame parities with its centre glow recoded to %10
(light blue: it fades in with the hull), blocks $88-$8B.
The timeline (segments INTROTAB, $9E00-$9FFF, and INTROTAB2, $A300-$A5FF): a column per register, one entry a frame, written in the vertical
blank for the next frame.
  python3 gen_intro.py
"""
import numpy as np
import gen_cosmic as g

SPRY = 139
BALLX = 184 - 12                      # goldfly's SPRX
BLK0 = 0x80                           # ($A000 - $8000) / 64
FADEBLK = 0x88

def balls():
    src = open("orbit.inc").read()
    i = src.index("balls:")
    vals = []
    for line in src[i:].split("\n")[1:]:
        if line.strip().startswith(";"): continue
        if ".byte" not in line: break
        for v in line.split(".byte")[1].split(";")[0].split(","):
            v = v.strip()
            vals.append(int(v[1:], 16) if v.startswith("$") else int(v))
    assert len(vals) >= 512
    return bytes(vals[:512])

def ship(par):
    s = g.sprites()
    f = np.zeros((21, 24), int)
    for side in (0, 1):
        blk = (16 + par * 2 + side) * 64
        for r in range(21):
            bits = int.from_bytes(s[blk + 3 * r:blk + 3 * r + 3], "big")
            for c in range(12): f[r, side * 12 + c] = (bits >> (22 - 2 * c)) & 3
    return f

def blocks(f):
    out = bytearray()
    for side in (0, 1):
        b = bytearray(64)
        for r in range(21):
            bits = 0
            for c in range(12): bits = bits << 2 | int(f[r, side * 12 + c])
            b[3 * r:3 * r + 3] = bits.to_bytes(3, "big")
        out += b
    return out

def fade_frames():
    out = bytearray()
    for par in (0, 1):
        f = ship(par)
        # the centre glow (between the engines: mc columns 10..13, rows 9..12) -> %10
        for r in range(9, 13):
            for c in range(10, 14):
                if f[r, c] == 3: f[r, c] = 2
        out += blocks(f)
    return out

ss = lambda u: u * u * (3 - 2 * u)

def timeline():
    T = []                            # p0, p1, x0, x1, y, en, c (d027/8), m0 (d025), m1 (d026; $ff: the glow)
    for t in range(2):                # hold (the light has been alone since goldfly's bars flew off)
        T.append((BLK0 + 7, BLK0 + 7, BALLX, BALLX, SPRY, 1, 7, 8, 1))
    for size in (6, 5, 4, 3, 2, 1):   # shrink
        for t in range(6):
            T.append((BLK0 + size, BLK0 + size, BALLX, BALLX, SPRY, 1, 7, 8, 1))
    NS = 42                           # split: two ball-1s glide to the engines (centres x 176.6 / 191.4, y 147.0)
    cy = [(7, 8), (8, 9), (9, 0), (0, 0)]
    for t in range(NS):
        u = ss((t + 1) / NS)
        x0 = round(BALLX + (164.6 - BALLX) * u)
        x1 = round(BALLX + (179.4 - BALLX) * u)
        y = round(SPRY + (136.5 - SPRY) * u)
        k = min(3, t * 4 // NS)
        c, m0 = cy[k]
        m1 = 1 if t < NS // 2 else 0xFF
        T.append((BLK0 + 1, BLK0 + 1, x0, x1, y, 3, c, m0, m1))
    # the ship: the engines only (hull black), then the hull fades in
    hull = [(0, 0), (6, 0), (11, 6), (4, 11), (14, 4)]   # (light blue %10, purple %01) steps
    for c, m0 in hull:
        for t in range(12):
            T.append((FADEBLK, FADEBLK + 1, 160, 184, SPRY, 3, c, m0, 0xFF))
    return T

def main():
    T = timeline()
    assert len(T) <= 160, len(T)
    L = ["; generated by gen_intro.py: cosmicstrings's intro (the light -> the ship's engine lights -> the ship)",
         f"INTRON = {len(T)}", '.segment "INTROSPR"', "introspr:"]
    data = balls() + fade_frames()
    for i in range(0, len(data), 16):
        L.append("        .byte " + ",".join(f"${b:02x}" for b in data[i:i + 16]))
    L.append('.segment "INTROTAB"')
    for e in T: assert e[1] == (e[0] if e[0] < FADEBLK else e[0] + 1)      # (p1 is implied: the same ball, or the fade frame's right half)
    for k, name in enumerate(["it_p0", "it_p1", "it_x0", "it_x1", "it_y", "it_en", "it_c", "it_m0", "it_m1"]):
        if name == "it_p1": continue
        if name == "it_y": L.append('.segment "INTROTAB2"')
        col = [e[k] for e in T]
        L.append(f"{name}:")
        for i in range(0, len(col), 16):
            L.append("        .byte " + ",".join(f"${b:02x}" for b in col[i:i + 16]))
    open("intro.inc", "w").write("\n".join(L) + "\n")
    print("intro.inc:", len(T), "frames,", len(data), "sprite bytes,", 8 * len(T), "table bytes")

if __name__ == "__main__":
    main()
