#!/usr/bin/env python3
"""Generate lookup tables for raybars.s (writes tables.inc).

Every angle is in "brads": 256 units = one full circle, so angle maths wraps
for free in an 8-bit register.  Coordinates are in scanlines.

Geometry (side view, the bars are cylinders lying along the screen's X axis):

        +y = down the screen
        +z = toward the camera
        camera at z = +infinity (orthographic) -> view vector V = (0, 1) in (y,z)

    A surface normal at angle t is N = (sin t, cos t).  For scanline i of a bar
    of radius R, sin t = (i + 0.5 - R) / R, so t depends ONLY on i: the normals
    of every scanline of every bar are a constant 24-byte table.

    Light direction at angle p:  L = (sin p, cos p)
        diffuse  = N.L          = cos(t - p)
        specular = (Rl.V)^n     = cos(2t - p)^n     (Rl = L mirrored about N)
        env map  = env(2t)                          (V mirrored about N)
    So shading a scanline is three table lookups indexed by sums of angles.
"""
import math, os

R = 16                    # bar radius in scanlines (bar height = 32)
BARH = 2 * R
Y_AMP = 64                # orbit radius, vertical (scanlines)
Z_AMP = 40                # orbit radius, depth
L_AMP = 44                # light vertical bob
LOGK = 32                 # log2 table scale: log2tab[n] = 32*log2(n)

def brad(rad):
    return rad * 128.0 / math.pi

def rad(b):
    return b * math.pi / 128.0

def sbyte(v):
    v = int(round(v))
    assert -128 <= v <= 127, v
    return v & 255

def ubyte(v):
    v = int(round(v))
    assert 0 <= v <= 255, v
    return v

tables = {}

# --- motion ---------------------------------------------------------------
tables["ysin"] = [sbyte(Y_AMP * math.sin(rad(a))) for a in range(256)]
tables["zcos"] = [sbyte(Z_AMP * math.cos(rad(a))) for a in range(256)]
tables["lsin"] = [sbyte(L_AMP * math.sin(rad(a))) for a in range(256)]

# --- 8-bit atan2 via logarithms ---------------------------------------------
# atan(y/x) = atan(2^(log2 y - log2 x)), so a division becomes a subtraction.
tables["log2tab"] = [0] + [min(255, int(round(LOGK * math.log2(n)))) for n in range(1, 256)]
tables["atanhi"] = [min(64, ubyte(brad(math.atan(2 ** (d / LOGK))))) for d in range(256)]   # y >= x
tables["atanlo"] = [ubyte(brad(math.atan(2 ** (-d / LOGK)))) for d in range(256)]           # y <  x

# --- shading (all doubled to 512 bytes, see raybars.s "pointer pre-offset") --
def doubled(f):
    t = [ubyte(f(a)) for a in range(256)]
    return t + t

# diffuse: 0..10 (one per step of the stretched ramps, see RAMPS)
tables["difftab"] = doubled(lambda a: 10 * max(0.0, math.cos(rad(a))))
# specular, Phong exponent 24: 0..6
tables["spectab"] = doubled(lambda a: 6 * max(0.0, math.cos(rad(a))) ** 24)

# environment map, 1-D: indexed by the angle of the reflected view ray.
# A chrome-style horizon: sky (up, -y) = 2, a horizon band = 1, ground = 0.
def env(a):
    up = -math.sin(rad(a))
    return 2 if up > 0.30 else 1 if up > -0.10 else 0
tables["envtab"] = doubled(env)

# --- per-scanline normals of a bar --------------------------------------------
theta = [brad(math.asin((i + 0.5 - R) / R)) for i in range(BARH)]
tables["theta"] = [sbyte(t) for t in theta]
tables["theta2"] = [sbyte(2 * t) for t in theta]

# --- emit ------------------------------------------------------------------------
order = ["difftab", "spectab", "envtab",                # 512 each, page aligned
         "ysin", "zcos", "lsin", "log2tab", "atanhi", "atanlo",   # 256 each
         "theta", "theta2"]
out = ["; Generated by gen_tables.py -- do not edit by hand.",
       f"; R={R} BARH={BARH} Y_AMP={Y_AMP} Z_AMP={Z_AMP} L_AMP={L_AMP}", ""]
for name in order:
    data = tables[name]
    out.append(f"{name}:")
    for i in range(0, len(data), 16):
        out.append("        .byte " + ",".join(f"${b:02x}" for b in data[i:i + 16]))
    out.append("")

here = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(here, "tables.inc"), "w") as f:
    f.write("\n".join(out))

# --- stretched colour ramps ----------------------------------------------------
# Ramps from "Stretching the c64 Palette" (Daniel Krajzewicz,
# krajzewicz.de/blog/stretching-the-c64-palette.php): "multichrome"
# gradients that take ONE colour from each of the VIC-II's brightness
# levels, whatever its hue, so a gradient gets every brightness step the
# chip has instead of the 3-4 a single hue offers.  The article's white
# end is dropped here (white is reserved for the specular highlight).
#
# Between each pair of neighbours there is a MIXED step, as in the
# article: the two colours on alternating scanlines, which a PAL TV
# blends.  7 colours -> 13 steps.
#
# Intensity = diffuse (0..10) + env (0..2) + specular (0..6) = 0..18
#   0..12  the bar's own colours, alternating with the in-between mixes
#   13     highlight fringe: brightest bar colour mixed with white
#   14+    specular core: white
# Diffuse + env tops out at 12, so only the specular term reaches white.
WHITE = 1
RAMPS = [                        # the article's multichrome gradients
    ("fire",   [0, 9, 2, 8, 10, 15, 7]),  # blk brown red orange l.red l.grey yellow
    ("ocean",  [0, 6, 11, 4, 14, 3, 13]), # blk blue d.grey purple l.blue cyan l.green
    ("forest", [0, 9, 11, 8, 5, 15, 13]), # blk brown d.grey orange green l.grey l.green
    ("dusk",   [0, 6, 11, 4, 10, 3, 7]),  # blk blue d.grey purple l.red cyan yellow
]
RAMPLEN = 32

def stretch(base):
    """7 pure colours -> 32 (even, odd) pairs."""
    steps = []
    for i, c in enumerate(base):
        steps.append((c, c))
        if i + 1 < len(base):
            steps.append((c, base[i + 1]))       # the in-between mix
    steps.append((base[-1], WHITE))              # highlight fringe
    steps += [(WHITE, WHITE)] * (RAMPLEN - len(steps))
    return steps

def split(base):
    """STYLE 1, the article's "scaled split": no mixes, so the 13 steps
    snap to the 7 pure colours; the black lines are drawn by raybars.s.
    Same 64-byte slot per bar as the dithered ramps (the 2nd half unused)."""
    steps = [base[(i + 1) // 2] for i in range(13)]  # 0..12
    steps.append(base[-1])                               # 13: no fringe mix
    steps += [WHITE] * (2 * RAMPLEN - len(steps))
    return steps

out = ["; Generated by gen_tables.py -- do not edit by hand.",
       f"; Per bar: {RAMPLEN} bytes for even scanlines, then {RAMPLEN} for odd ones.", ""]
for name, base in RAMPS:
    st = stretch(base)
    out.append(f"ramp_{name}:")
    for half, label in ((0, "even lines"), (1, "odd lines")):
        col = [p[half] for p in st]
        out.append(f"        ; {label}")
        for i in range(0, RAMPLEN, 16):
            out.append("        .byte " + ",".join(f"${c:02x}" for c in col[i:i + 16]))
    out.append("")
with open(os.path.join(here, "ramps_dither.inc"), "w") as f:
    f.write("\n".join(out))

out = ["; Generated by gen_tables.py -- do not edit by hand.",
       "; Per bar: 64 bytes, one ramp for every line.", ""]
for name, base in RAMPS:
    col = split(base)
    out.append(f"ramp_{name}:")
    for i in range(0, len(col), 16):
        out.append("        .byte " + ",".join(f"${c:02x}" for c in col[i:i + 16]))
    out.append("")
with open(os.path.join(here, "ramps_split.inc"), "w") as f:
    f.write("\n".join(out))
print("wrote tables.inc, ramps_dither.inc, ramps_split.inc")
