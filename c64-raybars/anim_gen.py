#!/usr/bin/env python3
"""Generator for the anim0 program: anim_params.P -> anim.inc + anim_rec.bin + anim_prof.bin.

 * anim_rec.bin   the scene, frame by frame: a list of bars far to near, each
                  4 bytes: address of its first visible non-black colour in the
                  profile table (lo, hi), first line, rows - 1; $ff = "same list
                  as two frames ago" (the frame parity picks the colours).  Bars off
                  screen are left out, black rows at a bar's edges are trimmed.
 * anim_prof.bin  every bar thickness 1..TMAX as its C64 colours, top row first:
                  four sets (frame parity x parity of the bar's top line), the
                  flat blue ramp's flicker pairs; 0 = black = not drawn.  The bar's
                  light comes from its distance (2 F R / T) as in the previews.
 * anim.inc       constants and the pointer tables the program includes.

    python3 anim_gen.py            # writes the three files, prints sizes
"""
import numpy as np
import anim_params as ap
import anim_scene as sc
import anim1_floor as fv
import gen_cosmic as gc

P = ap.P
sc.configure(P)
F, R, H = fv.F, fv.R, fv.H
TMAX, v7 = P["TMAX"], fv.v7
PROF_BASE = 0x4000                  # anim.cfg puts the profile table here
RAMP, RAMP_L, Lstar = fv.RAMP, fv.RAMP_L, fv.Lstar

def profile_idx(T):
    """Ramp index of each of the T rows of a bar T lines thick (0 = black)."""
    d = 2 * F * R / T
    out = []
    for i in range(T):
        r = (i + (np.arange(8) + 0.5) / 8) * 2 / T - 1           # row i spans 8 samples
        lit = sum(gc.row_v3(d, v) for v in r) / 8
        out.append(int(np.argmin(np.abs(Lstar(np.array(lit)) - RAMP_L))))
    return out

PROF_IDX = {T: profile_idx(T) for T in range(1, TMAX + 1)}

def colours(T, fp, q0):
    """The T colours of a bar T thick, top row on a line of parity q0, frame parity fp."""
    return [v7.colour(RAMP[k], q0 ^ (i & 1), fp) if k else 0
            for i, k in enumerate(PROF_IDX[T])]

def frame_list(t):
    out = []
    for z, yc, key in sorted(sc.bars(t), key=lambda b: -b[2]):    # far first
        z = max(z, 0.6)
        T = max(1, min(TMAX, int(round(2 * F * R / z))))
        y0 = int(round(yc - T / 2))
        if y0 >= H or y0 + T <= 0 or not any(PROF_IDX[T][max(0, -y0):H - y0]):
            continue
        out.append((y0, T))
    return out

def visible(y0, T):
    """(first row, last row) of the bar's non-black rows that are on screen."""
    rows = [i for i in range(T) if PROF_IDX[T][i] and 0 <= y0 + i < H]
    if rows:
        assert rows == list(range(rows[0], rows[-1] + 1)), "black row inside a bar"
    return (rows[0], rows[-1]) if rows else None

def build():
    lists = [frame_list(t) for t in range(sc.T_END)]
    prof, off = bytearray(), {}
    for fam in range(4):
        for T in range(1, TMAX + 1):
            off[fam, T] = len(prof)
            prof += bytes(colours(T, fam >> 1, fam & 1))
    rec, prev = bytearray(), {}
    for f, lst in enumerate(lists):
        if lst == prev.get(f & 1):
            rec.append(0xFF)
        else:
            rec.append(len(lst))
            for y0, T in lst:
                r0, r1 = visible(y0, T)
                ptr = PROF_BASE + off[2 * (f & 1) + (y0 & 1), T] + r0
                rec += bytes([ptr & 255, ptr >> 8, y0 + r0, r1 - r0])
        prev[f & 1] = lst
    return lists, bytes(rec), bytes(prof), off

def compose_ref(lst, f):
    """What the 6502's update() must leave in the line buffer for frame f."""
    buf = [0] * H
    for y0, T in lst:
        cols = colours(T, f & 1, y0 & 1)
        for i, c in enumerate(cols):
            if c and 0 <= y0 + i < H:
                buf[y0 + i] = c
    return buf

def main():
    lists, rec, prof, off = build()
    open("anim_rec.bin", "wb").write(rec)
    open("anim_prof.bin", "wb").write(prof)
    with open("anim.inc", "w") as f:
        f.write("; generated by anim_gen.py from anim_params.py -- do not edit\n")
        f.write(f"T_END      = {sc.T_END}\n")
        f.write(f"TMAX       = {TMAX}\n")
        f.write(f"FIRST_LINE = {P['FIRST_LINE']}\n")
    n_bars = [len(l) for l in lists]
    print(f"{sc.T_END} frames, up to {max(n_bars)} bars; records {len(rec)} bytes, "
          f"profiles {len(prof)} bytes -> anim.inc, anim_rec.bin, anim_prof.bin")

if __name__ == "__main__":
    main()
