#!/usr/bin/env python3
"""Part 3's waves on the C64 (6 columns) as CHANGE STREAMS on part2c's engine.

The raster loop reads 7 byte patterns a line (6 columns + the idle byte), a page each, for the frame's parity:
two sets of 7 pages, S0 for even frames, S1 for odd ones (the flicker pairs make the colour bytes depend on the
frame parity).  Frame t shows S[t&1], which holds frame t-2 until the changes are applied: runs of changed bytes
(page, first line, length, bytes), found by comparing frame t with frame t-2.  S[t&1] is free during the two
blanks before frame t (frame t-2 has been drawn, frame t-1 shows the other set), so the runs of a frame are shared
between the two: the peak frames (about 290 changed bytes) cost more than one blank holds.

  part3c_tab.s   the initial pages (frames N-2 and N-1: the loop wraps) and the page address table
  part3c_str.bin the stream, 8 KB ROML banks, each blank = a record: [n runs] n x ([page][line][len] bytes); $ff = next bank
  part3c.inc     constants

    SPLITS=6 python3 part3c_gen.py
"""
import os, pickle, sys
os.environ.setdefault("SPLITS", "6")
import numpy as np

H = 200
BUDGET = 5800            # cycles of delta work in one blank (the blank has about 6.5 k; the rest is the engine)
C_BYTE, C_RUN = 14, 70   # cost model: cycles a byte, cycles a run

def load():
    frames, gh = pickle.load(open("/tmp/part3_frames.pkl", "rb"))
    N = len(frames)
    img = []
    for t in range(N):
        cols = frames[t]                                    # 200 x 6
        idle = np.array(gh[t], dtype=np.uint8)              # 200
        img.append(np.concatenate([cols, idle[:, None]], axis=1).astype(np.uint8))   # 200 x 7
    return img

MAXRUN = 120             # a run is at most 120 bytes: the copy loop counts down with bpl
GAP = 6                  # runs closer than this are merged (a run costs more than a few bytes)

def runs_between(a, b, parity):
    """runs of bytes where b differs from a: (page id, line, bytes); gaps of up to GAP equal bytes are copied too."""
    out = []
    for k in range(7):
        d = a[:, k] != b[:, k]
        y = 0
        while y < H:
            if d[y]:
                y1 = y + 1
                while y1 < H:
                    nxt = y1
                    while nxt < H and not d[nxt] and nxt - y1 < GAP: nxt += 1
                    if nxt < H and d[nxt]: y1 = nxt + 1
                    else: break
                for s0 in range(y, y1, MAXRUN):
                    out.append((parity * 7 + k, s0, bytes(b[s0:min(y1, s0 + MAXRUN), k].tolist())))
                y = y1
            else:
                y += 1
    return out

def main():
    img = load(); N = len(img)
    assert N % 2 == 0
    # per frame t: runs against frame t-2 (the loop wraps)
    deltas = [runs_between(img[(t - 2) % N], img[t], t & 1) for t in range(N)]
    # blank b_x (after frame x's rows) prepares frame x+1; the blank before frame t are b_{t-2} and b_{t-1}:
    # delta(t) is split between them: b_{t-2} takes runs while its budget lasts, the rest go to b_{t-1}
    blanks = [[] for _ in range(N)]
    load_ = [0] * N
    for t in range(N):
        x1 = (t - 2) % N; x2 = (t - 1) % N
        for r in sorted(deltas[t], key=lambda r: -len(r[2])):          # big runs first, each into the lighter of the two blanks
            cost = C_BYTE * len(r[2]) + C_RUN
            x = x1 if load_[x1] <= load_[x2] else x2
            blanks[x].append(r); load_[x] += cost
    # b_{x} also carries the rest of delta(x+1) (put there above by x2 = x): both lists are in blanks[x]
    worst = max(load_)
    print(f"{N} frames; runs {sum(len(d) for d in deltas)}; changed bytes {sum(len(r[2]) for d in deltas for r in d)}; "
          f"worst blank {worst} cycles (budget {BUDGET}), mean {int(np.mean(load_))}")
    # the stream: 8 KB banks, records never straddle
    banks, cur = [], bytearray()
    start = {}
    for x in range(N):
        rec = bytearray([len(blanks[x])])
        for page, line, data in blanks[x]:
            rec += bytes([page, line, len(data)]) + data
        assert len(blanks[x]) < 250
        if len(cur) + len(rec) > 0x2000 - 1:
            cur.append(0xFF); banks.append(bytes(cur).ljust(0x2000, b"\xff")); cur = bytearray()
        start[x] = (len(banks), len(cur))
        cur += rec
    banks.append(bytes(cur).ljust(0x2000, b"\xff"))
    open("part3c_str.bin", "wb").write(b"".join(banks))
    # the initial pages: S0 = frame N-2, S1 = frame N-1 (the first two blanks bring them to frames 0 and 1)
    with open("part3c_tab.s", "w") as f:
        f.write("; generated by part3c_gen.py -- do not edit\n.segment \"PAGES\"\n.export pages\n.align 256\npages:\n")
        for par, fr in ((0, N - 2), (1, N - 1)):
            for k in range(7):
                b = img[fr][:, k].tolist() + [0] * 56
                for i in range(0, 256, 16):
                    f.write("        .byte " + ",".join(str(v) for v in b[i:i + 16]) + "\n")
    sb, so = start[N - 2]
    open("part3c.inc", "w").write(f"; generated by part3c_gen.py\nIMGBANKS = 1\nNF = {N}\nNBANKS = {len(banks)}\nSTART_BANK = {sb}\nSTART_OFF = {so}\n")
    print(f"stream: {len(banks)} bank(s) of 8 KB")

if __name__ == "__main__":
    main()
