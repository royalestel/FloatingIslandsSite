#!/usr/bin/env python3
"""Generator for animsplit (stage 2: the wave on the floor, 6 raster-split segments a line).

 * wave.inc / wave_*.bin: the floor's strings, each one's shift tables (segment k,
   frame u of its tilt), the per-frame band (the lines that differ from the still
   floor and the strings to draw there) and the two still floors (one per frame
   parity), all from anim_params.WAVE and the floor at the end of the anim0 film.
 * ref(tw, fp): what each of the 6 segments must show on each of the 200 lines.

    python3 wave_gen.py
"""
import math
import numpy as np
import anim_params as ap
import anim_gen as g

W = ap.WAVE
SEGS, PAD, H = 6, 32, g.H
TILT, STAG = W["TILT_T"], W["STAG"]

# the floor's strings, nearest first: (top line y0, thickness T, first, last non-black row)
STR = []
for y0, T in reversed(g.frame_list(g.sc.T_END - 1)):
    nz = [i for i in range(T) if g.PROF_IDX[T][i]]
    STR.append((y0, T, nz[0], nz[-1]))
NS = len(STR)
USTART = [i * STAG if W["NEAR_FIRST"] else (NS - 1 - i) * STAG for i in range(NS)]
W_LEN = (NS - 1) * STAG + TILT + W["HOLD"]
assert W_LEN < 256 and NS <= 32 and TILT <= 40

def amp(i):
    return W["RISE"] * (STR[i][1] / STR[0][1]) ** W["RISE_EXP"]

def shift(i, tw, k):
    """Segment k's shift (<= 0: up) of string i at wave frame tw."""
    u = tw - USTART[i]
    if not 0 < u < TILT:
        return 0
    return -int(round(amp(i) * math.sin(math.pi * u / TILT) * (k + 0.5) / SEGS))

def band(tw):
    """(first line, last line, first string, last string) to rebuild at frame tw, or None."""
    top, bot = 10 ** 6, -10 ** 6
    for i, (y0, T, r0, r1) in enumerate(STR):
        if 0 < tw - USTART[i] < TILT:
            top = min(top, y0 + r0 + min(shift(i, tw, k) for k in range(SEGS)))
            bot = max(bot, y0 + r1)
    top, bot = max(top, 0), min(bot, H - 1)
    if top > bot:
        return None
    hit = [i for i, (y0, T, r0, r1) in enumerate(STR)
           if y0 + r0 + min(shift(i, tw, k) for k in range(SEGS)) <= bot and y0 + r1 >= top]
    return top, bot, min(hit), max(hit)

def ref(tw, fp):
    """6 segments x 200 lines of colours (0 = black) at wave frame tw, frame parity fp."""
    out = np.zeros((SEGS, H), int)
    for k in range(SEGS):
        for i in range(NS - 1, -1, -1):                      # far first
            y0, T, r0, r1 = STR[i]
            s = shift(i, tw, k)
            cols = g.colours(T, fp, (y0 + s) & 1)
            for r in range(r0, r1 + 1):
                if 0 <= y0 + s + r < H:
                    out[k, y0 + s + r] = cols[r]
    return out

def main():
    OFF = bytearray()
    for i in range(NS):
        for k in range(SEGS):
            OFF += bytes(shift(i, USTART[i] + u, k) & 255 for u in range(TILT + 1))
    rec = bytearray()
    for tw in range(W_LEN):
        b = band(tw)
        rec += bytes([255, 0, 0, 0] if b is None else list(b))
    still = [bytes(int(v) for v in ref(-1, fp)[0]) for fp in (0, 1)]          # shifts all zero: any segment
    open("wave_off.bin", "wb").write(OFF)
    open("wave_rec.bin", "wb").write(bytes(rec))
    open("wave_still.bin", "wb").write(still[0] + still[1])
    with open("wave.inc", "w") as f:
        f.write("; generated by wave_gen.py -- do not edit\n")
        f.write(f"NS = {NS}\nTILT = {TILT}\nW_LEN = {W_LEN}\nPAD = {PAD}\n")
        f.write(f"PROF_BASE = ${g.PROF_BASE:04x}\n")
        def tab(name, vals):
            f.write(f"{name}:\n" + "".join(f"        .byte {v & 255}\n" for v in vals))
        f.write(".macro WTABLES\n")
        tab("sy0", [y0 + r0 + PAD for y0, T, r0, r1 in STR])         # buffer index of the first row
        tab("sn", [r1 - r0 for y0, T, r0, r1 in STR])                # rows - 1
        tab("syp", [y0 & 1 for y0, T, r0, r1 in STR])                # parity of its top line
        tab("sust", USTART)
        for name, sel in (("splo", lambda a_: a_ & 255), ("sphi", lambda a_: a_ >> 8)):
            vals = []                                           # 4 sets of 32: fam * 32 + string
            for fam in range(4):
                row = [g.PROF_BASE + off_of(fam, T) + r0 for y0, T, r0, r1 in STR]
                vals += [sel(a_) for a_ in row] + [0] * (32 - NS)
            tab(name, vals)
        f.write("opt_lo:\n" + "".join(f"        .byte <(woff + {(i * SEGS + k) * (TILT + 1)})\n"
                                      for i in range(NS) for k in range(SEGS)))
        f.write("opt_hi:\n" + "".join(f"        .byte >(woff + {(i * SEGS + k) * (TILT + 1)})\n"
                                      for i in range(NS) for k in range(SEGS)))
        f.write(".endmacro\n")
    mx = max(((b[1] - b[0] + 1) if (b := band(t)) else 0) for t in range(W_LEN))
    print(f"{NS} strings, {W_LEN} wave frames, widest band {mx} lines -> wave.inc, wave_*.bin")

_lists, _rec, _prof, _off = g.build()
def off_of(fam, T):
    return _off[fam, T]

if __name__ == "__main__":
    main()
