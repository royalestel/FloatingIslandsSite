#!/usr/bin/env python3
"""Generator for part1p.prg: part 1 with the PROCEDURAL beginning (part1_proc.py is the spec of the 6502 code).

 part1p_tab.s    every table the program uses (sine, smoothstep, reciprocal, row shapes, dimming maps ...)
 part1p.inc      constants and the swatch tables: colour / idle byte by swatch, frame parity, line parity,
                 in two blocks of 32: the second has the line parities swapped (bars whose first line is odd)
 part1p_prof.bin the bar arrays of the stream part (frames T_STACK ..), each with + 32 if its first line is odd
 part1p_rec.bin  the stream: per frame its bars, 4 bytes each (address of the first visible row, first line, rows - 1);
                 $ff = same list as last frame

    python3 part1p_gen.py
"""
import numpy as np
import part1 as p1
import part1_proc as q
import preview_v10 as v10

gp = p1.gp
H = 200
T0 = q.T_STACK
PROF_BASE = 0x6800            # set by cfg_text() once the tables' size is known (the arrays follow the tables)

def tables():
    """name -> list of ints (bytes), in this order."""
    t = {}
    t["sin"] = [v & 255 for v in q.SIN]
    t["sk"] = [(v >> 5) & 255 for v in q.SIN]                      # the draw key's sine part (arithmetic >> 5)
    t["azs"] = [v & 255 for v in q.AZS]
    t["sb"], t["se"], t["sc"] = q.SB, q.SE, q.SC
    t["risel"] = [v & 255 for v in q.RISE]; t["riseh"] = [v >> 8 for v in q.RISE]
    t["zbfl"] = [v & 255 for v in q.ZBF]; t["zbfh"] = [v >> 8 for v in q.ZBF]
    n = q.ZMAX + 1
    t["kyl"] = [q.KY[z] & 255 for z in range(n)]; t["kyh"] = [q.KY[z] >> 8 for z in range(n)]
    t["tt"] = q.TT[:n]
    t["dx"] = q.DX
    t["dimt"] = [q.DIMT[i][c][k] for i in range(32) for c in range(2) for k in range(32)]
    full, off = [], []
    for T in range(0, 64):
        off.append(len(full)); full += q.FULL[T]
    t["full"] = full
    t["foffl"] = [o & 255 for o in off]; t["foffh"] = [o >> 8 for o in off]
    return t

def write_tab(path):
    t = tables()
    with open(path, "w") as f:
        f.write("; generated by part1p_gen.py -- do not edit\n.segment \"PTAB\"\n")
        for name, vals in t.items():
            f.write(f".export p_{name}\n")
            f.write(f"p_{name}:\n")
            for i in range(0, len(vals), 16):
                f.write("        .byte " + ",".join(str(v & 255) for v in vals[i:i + 16]) + "\n")
    return sum(len(v) for v in t.values())

def stream():
    """The stream part: bar arrays (+32 when the first line is odd) and the records of frames T0 .. T_END-1."""
    prof, off = bytearray(), {}
    def intern(a):
        k = bytes(a)
        if k not in off:
            off[k] = len(prof); prof.extend(k)
        return off[k]
    frames, same, prev = [], [], None
    for f in range(T0, p1.T_END):
        lst = p1.frame_list(f)
        bars = []
        for y0, T in lst:
            arr = [(k + 32 * (y0 & 1)) if k else 0 for k in p1.gp.PROF[T]]
            rows = [i for i, k in enumerate(arr) if k and 0 <= y0 + i < H]
            if rows:
                assert rows == list(range(rows[0], rows[-1] + 1))
                bars.append((y0, arr, rows[0], rows[-1]))
        key = [(y0, tuple(a)) for y0, a, r0, r1 in bars]
        frames.append(bars); same.append(key == prev and f != T0); prev = key
    for fr in frames:
        for y0, a, r0, r1 in fr:
            intern(a)
    return frames, same, bytes(prof), off

def swatch_tables():
    col, gh = [], []
    for fp in (0, 1):
        for rp in (0, 1):
            for blk in (0, 1):
                r = rp ^ blk
                col.append([v10.colour(k, r, fp) for k in p1.gp.LAD] + [0] * (32 - len(p1.gp.LAD)))
                gh.append([v10.ghost(k, r, fp) for k in p1.gp.LAD] + [0] * (32 - len(p1.gp.LAD)))
    return col, gh        # index (fp * 2 + rp) * 2 + block

CFG = """# generated by part1p_gen.py -- ld65 config for part1p.prg (BASIC "SYS 2061" stub, everything in the PRG)
#  $0801 code   $1800 swatch tables   $2000 row set (even frames)   $3000 row set (odd frames)
#  $4000 the procedural tables ({tab} bytes), then the stream's bar arrays and records.  $3FFF is the VIC's idle byte.
#  The 200-byte line buffer is at $0400 with 64 bytes of padding either side (bars are not clipped when drawn).
MEMORY {{
    ZP:       start = $0002, size = $00FE, type = rw;
    LOADADDR: start = $07FF, size = $0002, file = %O;
    MAIN:     start = $0801, size = $1800 - $0801, file = %O, fill = yes;
    TAB:      start = $1800, size = $0800, file = %O, fill = yes;
    ROWS0:    start = $2000, size = $1000, file = %O, fill = yes;
    ROWS1:    start = $3000, size = $1000, file = %O, fill = yes;
    PTAB:     start = $4000, size = {tab}, file = %O;
    PROF:     start = {prof0}, size = {prof}, file = %O;
    SCENE:    start = {scene0}, size = {scene}, file = %O;
}}
SEGMENTS {{
    ZEROPAGE: load = ZP,       type = zp;
    LOADADDR: load = LOADADDR, type = ro;
    EXEHDR:   load = MAIN,     type = ro;
    CODE:     load = MAIN,     type = rw;
    TABLES:   load = TAB,      type = ro, align = $100;
    ROWS0:    load = ROWS0,    type = rw;
    ROWS1:    load = ROWS1,    type = rw;
    PTAB:     load = PTAB,     type = ro;
    PROF:     load = PROF,     type = ro;
    SCENE:    load = SCENE,    type = ro;
}}
"""

def main():
    ntab = write_tab("part1p_tab.s")
    frames, same, prof, off = stream()
    prof0 = 0x4000 + ntab
    rec = bytearray()
    for fr, sm in zip(frames, same):
        if sm:
            rec.append(0xFF)
        else:
            rec.append(len(fr))
            for y0, a, r0, r1 in fr:
                ptr = prof0 + off[bytes(a)] + r0
                rec += bytes([ptr & 255, ptr >> 8, y0 + r0, r1 - r0])
    open("part1p_prof.bin", "wb").write(prof); open("part1p_rec.bin", "wb").write(rec)
    open("part1p.cfg", "w").write(CFG.format(tab=ntab, prof0=prof0, prof=len(prof), scene0=prof0 + len(prof),
                                           scene=len(rec)))
    col, gh = swatch_tables()
    with open("part1p.inc", "w") as f:
        f.write("; generated by part1p_gen.py -- do not edit\n")
        f.write(f"T_END = {p1.T_END}\nT_STACK = {T0}\nPH0 = {q.PH0}\nPINC = {q.INC}\nTMAX = {q.p1.TMAX}\nNSW = {len(p1.gp.LAD)}\n")
        f.write(f"T_B0 = {q.T_B0}\nT_C0 = {q.T_C0}\nT_ENTER0 = {q.T_ENTER[0]}\nT_ENTER1 = {q.T_ENTER[1]}\nT_ENTER2 = {q.T_ENTER[2]}\n")
        f.write(f"NB = {q.NB}\nNE = {q.NE}\nNC = {q.NC}\nZB0 = {q.ZB0}\nNZB = {len(q.ZBF)}\nZC0 = {q.ZC0}\nZ_EQ = {q.Z_EQ}\n")
        f.write(f"ZMIN = {q.ZMIN}\nZMAX = {q.ZMAX}\nDIM0 = {q.DIM0}\nNDIM = {q.DIMN}\n")
        f.write(f"SLOT0 = {q.SLOT[0]}\nSLOT1 = {q.SLOT[1]}\nSLOT2 = {q.SLOT[2]}\nPHK1 = {q.PHK[1]}\nPHK2 = {q.PHK[2]}\n")
        for name, tabs in (("colt", col), ("ght", gh)):
            f.write(f".macro {name.upper()}\n")
            for t_ in tabs:
                f.write("        .byte " + ",".join(str(v & 255) for v in t_) + "\n")   # 32 bytes a block
            f.write(".endmacro\n")
    print(f"tables {ntab} bytes; stream: {len(frames)} frames, {len(prof)} bytes of bar arrays, {len(rec)} bytes of records")

if __name__ == "__main__":
    main()
