#!/usr/bin/env python3
"""band.inc: the band scroller's font (SCROLLER_PLAN.md): xenon_font.asm (CharPad: 248 characters, 62 2x2 tiles) with every byte inverted, so the
background is %00 ($d021 = black) and the strokes %01 ($d022: dark grey), %10 ($d023: light red), %11 (colour RAM: yellow).  Tile t = characters
4t (top left), 4t+1 (top right), 4t+2 (bottom left), 4t+3 (bottom right).  Segment FONT ($0800 in VIC bank 0).

  python3 gen_band.py
"""
import re
src = open("xenon_font.asm").read()
blk = src[src.index("charset_data\n"):src.index("; CharSet Attribute")]
cs = [int(v, 16) for v in re.findall(r"\$([0-9A-F]{2})", blk)]
assert len(cs) == 248 * 8
inv = [b ^ 0xFF for b in cs]
# ASCII -> tile (mock_scroller.CODE)
CODE = {" ": 0x19, ".": 0x10, ",": 0x11, ";": 0x12, "?": 0x13, "!": 0x14, "(": 0x17, ")": 0x18, "-": 0x06, "+": 0x07,
        "'": 0x0F, '"': 0x0E, "&": 0x08, "/": 0x0A, ":": 0x01, "=": 0x02, "*": 0x04, "@": 0x0D, "$": 0x0C}
for i, ch in enumerate("ABCDEFGHIJKLM"): CODE[ch] = 0x1A + i
for ch, t in zip("NOPQRSTUVWXYZ", [0x28, 0x29, 0x2A, 0x2B, 0x2C, 0x2D, 0x2E, 0x2F, 0x30, 0x27, 0x31, 0x32, 0x33]): CODE[ch] = t
for i in range(10): CODE[str(i)] = 0x34 + i
L = ["; generated by gen_band.py: the Xenon font, inverted (see there)", '.segment "FONT"', "bandfont:"]
for i in range(0, len(inv), 16):
    L.append("        .byte " + ",".join(f"${b:02x}" for b in inv[i:i + 16]))
def rows(text):
    """40 character codes for the top and bottom rows of the tiles of `text`, centred"""
    t = [CODE.get(ch, CODE[" "]) for ch in text.upper()]
    pad = (20 - len(t)) // 2
    t = [CODE[" "]] * pad + t + [CODE[" "]] * (20 - len(t) - pad)
    top = [c for tl in t for c in (4 * tl, 4 * tl + 1)]
    bot = [c for tl in t for c in (4 * tl + 2, 4 * tl + 3)]
    return top, bot
L += ['.segment "CODE2"', "bandtest:                       ; M2: a test text: the screen's rows 1 and 2 (two rows of 40 characters)"]
for row in rows("XENON TEST"):
    for i in range(0, 40, 20):
        L.append("        .byte " + ",".join(str(b) for b in row[i:i + 20]))
L.append("bandtest_end:")
open("band.inc", "w").write("\n".join(L) + "\n")
print("band.inc:", len(inv), "bytes")
import json
json.dump(CODE, open("/tmp/band_code.json", "w"))
