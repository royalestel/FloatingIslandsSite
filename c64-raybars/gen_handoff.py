#!/usr/bin/env python3
"""handoff.inc: goldfly's first bar, as goldtwin draws it before goldfly starts.

goldfly.s (built with -Wa -DHANDOFF=0, its stand-alone start) is run in the 6502 simulator; the picture of its first HANDOFF frames
(nothing but one thin dim bar just above the light) is stored as a replay: per frame the raster line of the first lit row, the number
of rows, and their 5 segment colours.  goldtwin's idle bar A block plays it back in its last HANDOFF frames; goldfly (built with the
default -DHANDOFF=30) then starts that bar HANDOFF frames into its flight, and its frames are identical to the stand-alone ones from
there on (checked: 120 frames).
    python3 gen_handoff.py"""
import os, sys, contextlib, io, subprocess
HERE = os.path.dirname(os.path.abspath(__file__)); os.chdir(HERE)
HANDOFF = 30
def build(h):
    subprocess.run(["cl65", "-g", "-t", "none", "-C", "raybars.cfg", "-Wa", f"-DHANDOFF={h}", "-Ln", "goldfly.lbl", "-o", "goldfly.prg", "goldfly.s"], check=True)
build(0)
os.environ["FRAMES"] = str(HANDOFF + 2)
src = open("sim_goldfly.py").read()
ns = {"__file__": os.path.join(HERE, "sim_goldfly.py"), "__name__": "x"}
with contextlib.redirect_stdout(io.StringIO()):
    exec(compile(src[:src.index("# --- 3. render")], "sim_goldfly.py", "exec"), ns)
fr = ns["frames"]
build(HANDOFF)                                  # leave the production build in place
recs = []
for i in range(HANDOFF):
    assert len(fr[i]) == 1, "more than one bar in the first frames"
    line, n, rows = fr[i][0]
    lit = [r for r in range(n) if any(rows[r])]
    r0, r1 = lit[0], lit[-1] + 1
    recs.append((line + 2 + r0, r1 - r0, [list(rows[r]) for r in range(r0, r1)]))
MAXR = max(r[1] for r in recs)
REC = 2 + MAXR * 5
out = ["; Generated by gen_handoff.py -- do not edit by hand.",
       f"; goldfly's first {HANDOFF} frames (one thin dim bar): per frame y0 (raster line of its first lit row), rows, 5 colours per row.",
       f"REPLAYN = {HANDOFF}", f"REPLAYREC = {REC}", f"REPLAYMAX = {MAXR}", "replo:",
       "        .byte " + ",".join(f"<(replay + {i * REC})" for i in range(HANDOFF)), "rephi:",
       "        .byte " + ",".join(f">(replay + {i * REC})" for i in range(HANDOFF)), "replay:"]
for y0, cnt, rows in recs:
    flat = [c for row in rows for c in row] + [0] * ((MAXR - cnt) * 5)
    out.append(f"        .byte {y0},{cnt}," + ",".join(str(c) for c in flat))
open("handoff.inc", "w").write("\n".join(out) + "\n")
print("wrote handoff.inc:", HANDOFF, "frames, up to", MAXR, "rows, y0", recs[0][0], "->", recs[-1][0])
