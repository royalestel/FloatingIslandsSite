#!/usr/bin/env python3
"""PART 2's earthquake on the C64 (6 columns), the table way:

Each column is one byte pattern -- the still floor's colour bytes, a page each -- and the raster loop reads every
column at  pattern - shift + line  (`lda P,x` with X = line): shaking a column is changing the low byte of its
operand.  The shifts of every frame are precomputed (part2.shake_offsets, 6 columns): one table lookup and 7
patched bytes a frame.

Patterns (one page each, line n at offset C0 + n; zero margins):  colour bytes for frame parity 0 / 1, with ghost
swatches (used while every column has the same shift: the idle byte pattern G is right then) and with the ghost
swatches replaced by the nearest flat swatch (while the columns differ: no idle byte, the G pattern is zero).
Swatch parity follows the row's parity inside its bar, as in part 1.

    SPLITS=6 python3 part2c_gen.py      -> part2c.inc, part2c_tab.s, part2c.cfg
"""
import os
os.environ.setdefault("SPLITS", "6")
import numpy as np
import part2 as q2
import preview_v10 as v10

gp = q2.gp
H = 200
C0 = 28                       # line 0 of a pattern at page offset C0: shifts -28..+28 never cross the page
NF = q2.SHAKE                 # 1064 frames: the shakes, then the still floor for the waves

def floor_lines():
    """swatch index and in-bar parity of every line of the still floor."""
    tok, par = [0] * H, [0] * H
    for y0, T in reversed(gp.STR):                     # far first
        for i, k in enumerate(gp.PROF[T]):
            if k and 0 <= y0 + i < H:
                tok[y0 + i] = k; par[y0 + i] = i & 1
    return tok, par

def patterns():
    tok, par = floor_lines()
    pat = {}
    for fp in (0, 1):
        col_g, col_f, gh = [], [], []
        for y in range(H):
            k = tok[y]
            if not k:
                col_g.append(0); col_f.append(0); gh.append(0); continue
            lad = gp.LAD[k]
            col_g.append(v10.colour(lad, par[y], fp)); gh.append(v10.ghost(lad, par[y], fp))
            kf = k if not v10.ghost(lad, par[y], fp) else min(gp.FLAT, key=lambda j: abs(gp.RAMP_L[j] - gp.RAMP_L[k]))
            col_f.append(v10.colour(gp.LAD[kf], par[y], fp))
        pat[("g", fp)], pat[("f", fp)], pat[("h", fp)] = col_g, col_f, gh
    pat[("z", 0)] = [0] * H
    return pat

def offsets():
    """per frame: the 6 column shifts and whether they are all the same (ghost mode)."""
    out = []
    for t in range(NF):
        dy, dk = q2.shake_offsets(t)
        d = [dy + v for v in dk]
        out.append(d)
    return out

def page(vals):
    b = [0] * 256
    for n, v in enumerate(vals):
        b[C0 + n] = v & 255
    return b

PAGES = [("g", 0), ("g", 1), ("f", 0), ("f", 1), ("h", 0), ("h", 1), ("z", 0)]

def main():
    pat = patterns()
    offs = offsets()
    lo = max(max(d) for d in offs); hi = min(min(d) for d in offs)
    assert lo <= C0 and C0 - hi + H - 1 <= 255, (lo, hi)
    with open("part2c_tab.s", "w") as f:
        f.write("; generated by part2c_gen.py -- do not edit\n.segment \"PATS\"\n")
        for name, fp in PAGES:
            f.write(f".export pat_{name}{fp}\npat_{name}{fp}:\n")
            b = page(pat[(name, fp)])
            for i in range(0, 256, 16):
                f.write("        .byte " + ",".join(str(v) for v in b[i:i + 16]) + "\n")
        f.write(".segment \"OFFS\"\n.export offs\noffs:\n")    # per frame: 6 operand low bytes, mode
        for d in offs:
            rec = [(C0 - v) & 255 for v in d] + [1 if len(set(d)) == 1 else 0]
            f.write("        .byte " + ",".join(str(v) for v in rec) + "\n")
    open("part2c.inc", "w").write(f"; generated by part2c_gen.py\nNF = {NF}\nC0 = {C0}\n")
    print(f"{NF} frames; shifts {hi}..{lo} lines; {len(PAGES)} pattern pages; "
          f"{sum(1 for d in offs if len(set(d)) > 1)} frames with differing columns")

if __name__ == "__main__":
    main()
