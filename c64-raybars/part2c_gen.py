#!/usr/bin/env python3
"""PART 2's earthquake on the C64 (6 columns), the table way:

Each column is one byte pattern -- the still floor's colour bytes, a page each -- and the raster loop reads every
column at  pattern - shift + line  (`lda P,x` with X = line): shaking a column is changing the low byte of its
operand.  The shifts of every frame are precomputed (part2.shake_offsets, 6 columns): one table lookup and 7
patched bytes a frame.

Patterns (one page each, line n at offset C0 + n; zero margins):  colour bytes for frame parity 0 / 1, with ghost
swatches (used while every column has the same shift: the idle byte pattern G is right then) and with the ghost
swatches replaced by the nearest flat swatch (while the columns differ: no idle byte, the G pattern is zero).
Swatch parity follows the row's parity inside its bar, as in part 1.

    SPLITS=6 python3 part2c_gen.py      -> part2c.inc, part2c_tab.s, part2c.cfg
"""
import os, math
os.environ.setdefault("SPLITS", "6")
import numpy as np
import part2 as q2
import preview_v10 as v10

gp = q2.gp
H = 200
C0 = 28                       # line 0 of a pattern at page offset C0: shifts -28..+28 never cross the page
PLAT = os.environ.get("PLATFORM", "NTSC")
RATE = 1.0                                        # one film frame per displayed frame (NTSC 60 Hz: the 60 fps mock-up's timing, the one the music was timed to)
NF = int(math.ceil(q2.SHAKE / RATE))              # PAL 1064 / NTSC 1277 frames: the shakes, then the still floor for the waves

def floor_lines():
    """the still floor's token on every line, as part2.py's model draws it (the floor the waves start from = the floor part 1 ends on)."""
    seg = q2.make_seq()[0][1](-1)
    assert all(len({int(seg[k, y]) for k in range(q2.SEGS)}) == 1 for y in range(H))
    tok = [int(seg[0, y]) for y in range(H)]
    assert all(t < q2.RED for t in tok)
    return tok

def patterns():
    """colour bytes by SCREEN-row parity (pattern line n = screen line n at shift 0) and frame parity fp; the engine takes page
    fp EOR (shift & 1) for a shifted column (exact for every swatch whose row flip equals its frame flip: all but 3)."""
    tok = floor_lines()
    g2 = q2.gp2
    pat = {}
    for fp in (0, 1):
        col_g, col_f, gh = [], [], []
        for y in range(H):
            k = tok[y]
            if not k:
                col_g.append(0); col_f.append(0); gh.append(0); continue
            col_g.append(q2.colour(k, y, fp)); gh.append(q2.ghost(k, y, fp))
            kf = k if not q2.ghost(k, y, fp) else min(g2.FLAT, key=lambda j: abs(gp.RAMP_L[j] - g2.light(k)))     # as part2.fix_line
            col_f.append(q2.colour(kf, y, fp))
        pat[("g", fp)], pat[("f", fp)], pat[("h", fp)] = col_g, col_f, gh
    pat[("z", 0)] = [0] * H
    return pat

def offsets():
    """per frame: the 6 column shifts and whether they are all the same (ghost mode)."""
    out = []
    for t in range(NF):
        dy, dk = q2.shake_offsets(t * RATE)
        d = [dy + v for v in dk]
        out.append(d)
    return out

def pack(offs):
    """the shifts as a packed stream: a frame = 3 bytes, 6 nibbles (shift + 8: -8..6 -> 0..14); `$ff, n` = keep the last shifts for n more frames (1..255)."""
    out, i, prev = bytearray(), 0, None
    while i < len(offs):
        d = offs[i]
        if d == prev:
            n = 1
            while i + n < len(offs) and offs[i + n] == d and n < 255: n += 1
            out += bytes([0xFF, n]); i += n
        else:
            ns = [v + 8 for v in d]
            assert all(0 <= v <= 14 for v in ns), d
            out += bytes([ns[0] << 4 | ns[1], ns[2] << 4 | ns[3], ns[4] << 4 | ns[5]]); prev = d; i += 1
    return bytes(out)

def page(vals):
    b = [0] * 256
    for n, v in enumerate(vals):
        b[C0 + n] = v & 255
    return b

PAGES = [("g", 0), ("g", 1), ("f", 0), ("f", 1), ("h", 0), ("h", 1), ("z", 0)]

def main():
    pat = patterns()
    offs = offsets()
    lo = max(max(d) for d in offs); hi = min(min(d) for d in offs)
    assert lo <= C0 and C0 - hi + H - 1 <= 255, (lo, hi)
    with open("part2c_tab.s", "w") as f:
        f.write("; generated by part2c_gen.py -- do not edit\n.segment \"PATS\"\n")
        for name, fp in PAGES:
            f.write(f".export pat_{name}{fp}\npat_{name}{fp}:\n")
            b = page(pat[(name, fp)])
            for i in range(0, 256, 16):
                f.write("        .byte " + ",".join(str(v) for v in b[i:i + 16]) + "\n")
        stream = pack(offs)
        f.write(".segment \"OFFS\"\n.export offs\noffs:\n")                  # the packed shifts
        for i in range(0, len(stream), 24):
            f.write("        .byte " + ",".join(str(v) for v in stream[i:i + 24]) + "\n")
    open("part2c.inc", "w").write(f"; generated by part2c_gen.py\nNF = {NF}\nC0 = {C0}\n")
    print(f"{PLAT}: packed stream {len(stream)} bytes (was {7 * NF}); {NF} frames; shifts {hi}..{lo} lines; {len(PAGES)} pattern pages; "
          f"{sum(1 for d in offs if len(set(d)) > 1)} frames with differing columns")

if __name__ == "__main__":
    main()
