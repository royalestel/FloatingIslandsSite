#!/usr/bin/env python3
"""Builds routine.crt (EasyFlash): bank 0 = the boot (ROMH), banks 1.. = the program image (ROML), then
the scene stream (ROML, read in place by update).

    python3 mk_cart.py            -> part1c.prg, cartboot.bin, routine.crt
"""
import struct, subprocess, sys
import part1_gen as g

import os
WAITX = int(os.environ.get('WAITX', 6))
HTUNE = int(os.environ.get('HTUNE', 0))

def run(cmd):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode:
        sys.exit(r.stdout + r.stderr)

def main():
    banks, prof = g.scene_banks()
    prof_end = g.PROF_BASE + len(prof)
    img_len = prof_end - 0x0801
    img_banks = -(-img_len // 0x2000)
    scene_bank = 1 + img_banks
    # part1.s as a cartridge program: everything up to the end of the profile table, no scene
    open("part1c.cfg", "w").write(f"""# generated by mk_cart.py -- the cartridge build of part1: the image copied to RAM by the boot
MEMORY {{
    ZP:       start = $0002, size = $00FE, type = rw;
    LOADADDR: start = $07FF, size = $0002, file = %O;
    MAIN:     start = $0801, size = $1800 - $0801, file = %O, fill = yes;
    TAB:      start = $1800, size = $0800, file = %O, fill = yes;
    ROWS0:    start = $2000, size = $1000, file = %O, fill = yes;
    ROWS1:    start = $3000, size = $1000, file = %O, fill = yes;
    PROF:     start = $4000, size = {len(prof)}, file = %O;
}}
SEGMENTS {{
    ZEROPAGE: load = ZP,       type = zp;
    LOADADDR: load = LOADADDR, type = ro;
    EXEHDR:   load = MAIN,     type = ro;
    CODE:     load = MAIN,     type = rw;
    TABLES:   load = TAB,      type = ro, align = $100;
    ROWS0:    load = ROWS0,    type = rw;
    ROWS1:    load = ROWS1,    type = rw;
    PROF:     load = PROF,     type = ro;
}}
""")
    run(["cl65", "-g", "-t", "none", "-C", "part1c.cfg", "-Wa", "-DCART=1", "-Wa", f"-DSCENE_BANK={scene_bank}", "-Wa", f"-DWAITX={WAITX}", "-Wa", f"-DHTUNE={HTUNE}",
         "-Ln", "part1c.lbl", "-o", "part1c.prg", "part1.s"])
    prg = open("part1c.prg", "rb").read()
    assert prg[0] | prg[1] << 8 == 0x07FF or True
    image = prg[2:]                                       # from $07FF: the 2 load-address bytes are the first
    # the PRG's first two bytes are the load address ($0801); the stub at $0801 follows
    image = prg[2:]
    assert len(image) == img_len, (len(image), img_len)
    lbl = {l.split()[2].lstrip("."): int(l.split()[1], 16) for l in open("part1c.lbl")}
    open("cartboot.inc", "w").write(f"IMG_PAGES = {-(-img_len // 256)}\nPROG_START = ${lbl['start']:04x}\n")
    run(["ca65", "-o", "cartboot.o", "cartboot.s"])
    run(["ld65", "-C", "cartboot.cfg", "-o", "cartboot.bin", "cartboot.o"])
    boot = open("cartboot.bin", "rb").read()
    assert len(boot) == 0x2000, len(boot)

    chips = []
    def chip(bank, addr, data):
        assert len(data) == 0x2000
        chips.append(b"CHIP" + struct.pack(">IHHHH", 0x2010, 2, bank, addr, 0x2000) + data)
    chip(0, 0x8000, b"\xff" * 0x2000)
    chip(0, 0xA000, boot)
    padded = image.ljust(img_banks * 0x2000, b"\xff")
    for b in range(img_banks):
        chip(1 + b, 0x8000, padded[b * 0x2000:(b + 1) * 0x2000])
    for b, data in enumerate(banks):
        chip(scene_bank + b, 0x8000, data)
    hdr = b"C64 CARTRIDGE   " + struct.pack(">IHHBB6x", 0x40, 0x0100, 32, 1, 0) + b"FLOATING ISLANDS".ljust(32, b"\0")
    open("routine.crt", "wb").write(hdr + b"".join(chips))
    print(f"routine.crt: {1 + img_banks + len(banks)} banks (boot, {img_banks} of program image, "
          f"{len(banks)} of scene from bank {scene_bank}); program image {img_len} bytes, start ${lbl['start']:04x}")

if __name__ == "__main__":
    main()
